package dev.vexelray.gui.iconplugin;

import java.util.List;
import java.util.Locale;
import java.util.regex.Pattern;

/**
 * The Java a baked set is named by: an enum, one constant per icon carrying its cells, implementing
 * {@code dev.vexelray.gui.icons.BakedIcon}; and its atlas, a {@code BakedAtlas} that opens the resource by a constant
 * name. Everything the two do beyond naming cells is in those hand-written types, so what is generated is data.
 */
final class Sources {

    /** Where {@code BakedIcon}, {@code BakedAtlas} and {@code IconSize} are: the suite's set's own package. */
    static final String RUNTIME = "dev.vexelray.gui.icons";

    static final String HEADER = "// Generated by vexelray-gui-icons-maven-plugin. Do not edit: change the art and build again.\n";

    /** A name in a set: lower case letters and digits, in words joined by single hyphens. */
    static final Pattern NAME = Pattern.compile("[a-z0-9]+(-[a-z0-9]+)*");

    private Sources() {
    }

    /** {@code pin-up} as {@code PIN_UP}; a name that starts with a number has it moved last: {@code 3d-models}, {@code MODELS_3D}. */
    static String constant(String name) {
        String s = name.replaceFirst("^([0-9][a-z0-9]*)-(.+)$", "$2-$1");
        String c = s.toUpperCase(Locale.ROOT).replace('-', '_');
        if (Character.isDigit(c.charAt(0))) {
            throw new IllegalArgumentException("'" + name + "' is a number alone, and a constant cannot start with one");
        }
        return c;
    }

    /** {@code PixIcon} as {@code pix-icon}: the atlas's file name when none is given. */
    static String kebab(String className) {
        return className.replaceAll("([a-z0-9])([A-Z])", "$1-$2").toLowerCase(Locale.ROOT);
    }

    /**
     * The enum: {@code names} in order with their cells, {@code atlasClass} for the cells' atlas. {@code base}, the
     * enum this set extends, is named in its documentation, and {@code from} says where the art is.
     */
    static String iconEnum(String pkg, String enumName, String atlasClass, List<String> names, int[] small, int[] large,
                           String base, String from) {
        StringBuilder s = new StringBuilder(HEADER).append("package ").append(pkg).append(";\n\n");
        s.append("import dev.vexelray.canvas.Color;\n");
        s.append("import dev.vexelray.gui.core.ImageField;\n");
        if (!pkg.equals(RUNTIME)) {
            s.append("import ").append(RUNTIME).append(".BakedIcon;\n");
            s.append("import ").append(RUNTIME).append(".IconSize;\n");
        }
        s.append("\n");
        s.append("/**\n");
        s.append(" * Every icon in this set, by name: one distance field per drawing, all in one atlas the renderer uploads\n");
        s.append(" * itself. {@code ").append(enumName).append(".").append(constant(names.get(0)))
                .append(".field(16, tint)} is a field to hand a node; an {@code IconView} shows one\n");
        s.append(" * and keeps it right as it resizes and changes state.\n");
        if (base != null) {
            s.append(" *\n * <p>An extension of {@link ").append(base).append("}: baked at its grids, and using none of its names.\n");
        }
        s.append(" *\n * <p>Generated by {@code vexelray-gui-icons-maven-plugin}\n * from ").append(from)
                .append(".\n * Do not edit: change the art and build again.\n */\n");
        s.append("public enum ").append(enumName).append(" implements BakedIcon {\n\n");
        for (int i = 0; i < names.size(); i++) {
            String n = names.get(i);
            s.append("    /** {@code ").append(n).append("}");
            if (small[i] < 0 || large[i] < 0) {
                s.append(": ").append(small[i] < 0 ? "large" : "small").append(" art only");
            }
            s.append(". */\n");
            s.append("    ").append(constant(n)).append("(\"").append(n).append("\", ").append(small[i]).append(", ")
                    .append(large[i]).append(")").append(i == names.size() - 1 ? ";\n" : ",\n");
        }
        s.append("""

                    private final String file;
                    private final int small;
                    private final int large;

                    %1$s(String file, int small, int large) {
                        this.file = file;
                        this.small = small;
                        this.large = large;
                    }

                    @Override
                    public String file() {
                        return file;
                    }

                    @Override
                    public boolean drawn(IconSize size) {
                        return (size == IconSize.SMALL ? small : large) >= 0;
                    }

                    @Override
                    public ImageField field(IconSize size, Color tint) {
                        boolean useSmall = size == IconSize.SMALL ? small >= 0 : large < 0;
                        return useSmall ? %2$s.INSTANCE.small(small, tint) : %2$s.INSTANCE.large(large, tint);
                    }

                    /** The icon named {@code file} in this set, or null if there is none. */
                    public static %1$s named(String file) {
                        for (%1$s icon : values()) {
                            if (icon.file.equals(file)) {
                                return icon;
                            }
                        }
                        return null;
                    }
                }
                """.formatted(enumName, atlasClass));
        return s.toString();
    }

    /** The atlas: its size, its grids, and the resource it opens, {@code resource} from the class path's root. */
    static String atlas(String pkg, String atlasClass, String enumName, String resource, Atlas atlas, Grids g) {
        String imports = pkg.equals(RUNTIME) ? "" : "import " + RUNTIME + ".BakedAtlas;\n\n";
        return HEADER + "package " + pkg + ";\n\n" + imports + """
                import java.io.InputStream;

                /** The atlas every {@link %2$s} is a cell of. Generated by {@code vexelray-gui-icons-maven-plugin} with it. */
                final class %1$s extends BakedAtlas {

                    static final %1$s INSTANCE = new %1$s();

                    static final String RESOURCE = "%3$s";

                    private %1$s() {
                        super(%4$d, %5$d, %6$d, %7$d, %8$d, %9$d, %10$d);
                    }

                    @Override
                    protected InputStream open() {
                        return %1$s.class.getResourceAsStream("%3$s");
                    }

                    @Override
                    protected String resource() {
                        return RESOURCE;
                    }
                }
                """.formatted(atlasClass, enumName, resource, atlas.width(), atlas.height(), atlas.smallTop(),
                g.largeInner(), g.largeSpread(), g.smallInner(), g.smallSpread());
    }
}
